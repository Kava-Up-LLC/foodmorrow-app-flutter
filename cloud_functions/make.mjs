// Stitches each deployable function out of `_shared.mjs` + `parts/<name>.mjs`.
// Cloud Code deploys one file per function, so the shared helpers have to live in every file.
// Run after touching either half:  node cloud_functions/make.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const here = new URL('.', import.meta.url);
const read = (p) => readFileSync(new URL(p, here), 'utf8');

const FUNCTIONS = {
  hello: 'Called on every app start: upserts the seller, returns the business name and week start.',
  profile: 'Settings: reads the seller, or changes the business name / week start.',
  products: 'The menu: list, add, edit, remove (archive). Always answers with the whole active menu.',
  orders: 'Orders: the week strip, search, one order, save, picked up and delete.',
  home: 'What to make tomorrow, added up across every order, plus today’s pickups.',
};

const shared = read('_shared.mjs')
  .split('\n')
  // Drop only the three-line note at the top, not the import under it.
  .filter((line, i) => !(i < 3 && line.startsWith('//')))
  .join('\n')
  .trimStart();

for (const [name, what] of Object.entries(FUNCTIONS)) {
  const header = [
    `// ${name} — ${what}`,
    '// Runs on AppAmbit Cloud Code. HTTP trigger: /api/fn/' + name + '. Deployed to both apps',
    '// (Foodmorrow App - iOS, Foodmorrow App - Android), which share the database FoodmorrowDb.',
    '//',
    '// GENERATED by cloud_functions/make.mjs from _shared.mjs + parts/' + name + '.mjs — do not edit by hand.',
    '',
    '// ---- shared (the same block in every Foodmorrow function: Cloud Code deploys single files)',
  ].join('\n');
  writeFileSync(new URL(`${name}.mjs`, here), `${header}\n${shared}\n${read(`parts/${name}.mjs`)}`);
  console.log(`wrote ${name}.mjs`);
}
